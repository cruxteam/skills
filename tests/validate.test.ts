import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const VALIDATOR = join(ROOT, "skills/crux-config/scripts/validate.mjs");
const fixture = (name: string) => join(import.meta.dir, "fixtures", name, ".crux");

/** The rules version the bundle was built from, read from its generated banner. */
const bannerVersion = () => {
  const match = readFileSync(VALIDATOR, "utf8").match(/^\/\/ RULES_VERSION (\d+)$/m);
  if (!match) throw new Error("validate.mjs has no RULES_VERSION banner");
  return Number(match[1]);
};

const run = (runtime: string, ...args: string[]) => {
  const proc = Bun.spawnSync([runtime, VALIDATOR, ...args], { cwd: ROOT });
  return { exitCode: proc.exitCode, stdout: proc.stdout.toString(), stderr: proc.stderr.toString() };
};

test("validate.mjs carries the generated banner", () => {
  expect(readFileSync(VALIDATOR, "utf8")).toContain(
    "// GENERATED by `bun run plugin:build-validator` from @crux/workflow-types — do not edit.",
  );
});

describe.each(["bun", "node"])("validate.mjs under %s", (runtime) => {
  test("passes a valid .crux/ and reports the rules version in its banner", () => {
    const r = run(runtime, "--json", fixture("valid"));
    expect(r.exitCode).toBe(0);
    expect(JSON.parse(r.stdout)).toMatchObject({ rulesVersion: bannerVersion(), valid: true });
  });

  test("fails a .crux/ with a stray entry and names it", () => {
    const r = run(runtime, fixture("stray-entry"));
    expect(r.exitCode).toBe(1);
    expect(r.stderr).toContain("error README.md: unknown entry");
  });
});
